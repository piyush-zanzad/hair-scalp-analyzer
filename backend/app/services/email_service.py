import os
import json
import shutil
from pathlib import Path
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders
import logging

logger = logging.getLogger("uvicorn.error")

class EmailService:
    @staticmethod
    def send_pdf_report(recipient_email: str, patient_name: str, pdf_path: str, scan_id: str):
        """
        Dispatches the diagnostic PDF report to the patient.
        If SMTP server details are set in the environment, it sends a real email.
        Otherwise, it logs the transaction and saves a copy to static/sent_emails/ for verification.
        """
        subject = f"Diagnostic Scalp Report - {patient_name} (Scan ID: {scan_id})"
        body = f"""Dear {patient_name},

Please find attached your Scalp & Hair analysis diagnostic report (Scan ID: {scan_id}) generated by the ScalpDiagnostix AI system.

This report contains:
- Preprocessed scalp magnification crops.
- Grad-CAM features activation heatmap.
- Hair loss stage and scalp condition classifications.
- Clinical practitioner comments.

If you have any questions, please contact your clinic.

Best regards,
Clinical AI Diagnostics Team
"""
        # Ensure static sent_emails output directory exists
        static_sent_dir = Path("backend/static/sent_emails")
        static_sent_dir.mkdir(parents=True, exist_ok=True)
        
        # Save a local JSON record of the email trigger for offline demonstration/testing
        email_record = {
            "to": recipient_email,
            "subject": subject,
            "body": body,
            "timestamp": os.path.getmtime(pdf_path) if os.path.exists(pdf_path) else None,
            "pdf_name": os.path.basename(pdf_path)
        }
        
        record_path = static_sent_dir / f"{scan_id}_email.json"
        try:
            with open(record_path, "w") as f:
                json.dump(email_record, f, indent=4)
                
            if os.path.exists(pdf_path):
                shutil.copy(pdf_path, static_sent_dir / os.path.basename(pdf_path))
                
            logger.info(f"Offline email record successfully saved for scan {scan_id} to {record_path}")
        except Exception as e:
            logger.error(f"Failed to save local offline email copy: {e}")

        # SMTP configuration (Load from settings file first, fallback to env)
        config_path = "backend/smtp_config.json"
        smtp_host = None
        smtp_port = None
        smtp_user = None
        smtp_pass = None
        smtp_from = "no-reply@scalpdiagnostix.com"
        
        if os.path.exists(config_path):
            try:
                with open(config_path, "r") as f:
                    config = json.load(f)
                    smtp_host = config.get("smtp_host")
                    smtp_port = config.get("smtp_port")
                    smtp_user = config.get("smtp_user")
                    smtp_pass = config.get("smtp_password")
                    smtp_from = config.get("smtp_from", "no-reply@scalpdiagnostix.com")
            except Exception as e:
                logger.warning(f"Error loading smtp_config.json: {e}")
                
        if not smtp_host:
            smtp_host = os.getenv("SMTP_HOST")
            smtp_port = os.getenv("SMTP_PORT")
            smtp_user = os.getenv("SMTP_USER")
            smtp_pass = os.getenv("SMTP_PASSWORD")
            smtp_from = os.getenv("SMTP_FROM", "no-reply@scalpdiagnostix.com")
        
        if not smtp_host or not smtp_user or not smtp_pass:
            logger.info("SMTP environment variables not set. Bypassing SMTP transmission (offline record written).")
            return False
            
        try:
            # Setup MIME message
            msg = MIMEMultipart()
            msg['From'] = smtp_from
            msg['To'] = recipient_email
            msg['Subject'] = subject
            
            msg.attach(MIMEText(body, 'plain'))
            
            # Attach PDF report
            if os.path.exists(pdf_path):
                with open(pdf_path, "rb") as attachment:
                    part = MIMEBase('application', 'octet-stream')
                    part.set_payload(attachment.read())
                    encoders.encode_base64(part)
                    part.add_header(
                        'Content-Disposition',
                        f"attachment; filename= {os.path.basename(pdf_path)}",
                    )
                    msg.attach(part)
                    
            # Connect to SMTP server
            port = int(smtp_port) if smtp_port else 587
            server = smtplib.SMTP(smtp_host, port)
            server.starttls()
            server.login(smtp_user, smtp_pass)
            server.sendmail(smtp_from, recipient_email, msg.as_string())
            server.quit()
            logger.info(f"Successfully sent PDF email report to {recipient_email} via SMTP.")
            return True
        except Exception as e:
            logger.error(f"SMTP mail server dispatch failed: {e}")
            return False
